import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outputFile = path.join(rootDir, 'src', 'generated', 'skill-catalog.ts')
const excludedDirs = new Set(['.git', 'node_modules', 'lib'])

const skillFiles = await findSkillFiles(rootDir)
const skills = []
const seenIds = new Set()

for (const file of skillFiles) {
  const content = stripBom(await readFile(file, 'utf8'))
  const metadata = parseFrontmatter(content, file)
  const id = skillIdForFile(file)

  if (seenIds.has(id)) {
    throw new Error(`Duplicate skill id: ${id}`)
  }
  seenIds.add(id)

  skills.push({
    id,
    name: metadata.name,
    description: metadata.description,
    content
  })
}

skills.sort((a, b) => a.id.localeCompare(b.id))

await mkdir(path.dirname(outputFile), { recursive: true })
await writeFile(outputFile, renderCatalog(skills), 'utf8')

console.log(`Generated ${path.relative(rootDir, outputFile)} with ${skills.length} skills.`)

async function findSkillFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    if (entry.name.startsWith('.') && entry.name !== '.github') {
      continue
    }

    const fullPath = path.join(dir, entry.name)

    if (entry.isDirectory()) {
      if (!excludedDirs.has(entry.name)) {
        files.push(...await findSkillFiles(fullPath))
      }
      continue
    }

    if (entry.isFile() && entry.name === 'SKILL.md') {
      files.push(fullPath)
    }
  }

  return files
}

function skillIdForFile(file) {
  const relative = path.relative(rootDir, file).split(path.sep).join('/')

  if (relative === 'SKILL.md') {
    return 'root'
  }

  if (!relative.endsWith('/SKILL.md')) {
    throw new Error(`Unexpected skill path: ${relative}`)
  }

  return relative.slice(0, -'/SKILL.md'.length)
}

function parseFrontmatter(content, file) {
  const match = content.match(/^---[ \t]*\r?\n([\s\S]*?)\r?\n---[ \t]*(?:\r?\n|$)/)
  const relative = path.relative(rootDir, file)

  if (!match) {
    throw new Error(`${relative}: missing frontmatter`)
  }

  const values = parseYamlSubset(match[1], relative)
  const name = values.name?.trim()
  const description = values.description?.trim()

  if (!name) {
    throw new Error(`${relative}: frontmatter.name is required`)
  }

  if (!/^[a-z0-9][a-z0-9-]*$/.test(name)) {
    throw new Error(`${relative}: frontmatter.name must use lowercase kebab-case`)
  }

  if (!description) {
    throw new Error(`${relative}: frontmatter.description is required`)
  }

  return { name, description }
}

function parseYamlSubset(source, relative) {
  const lines = source.split(/\r?\n/)
  const values = {}

  for (let index = 0; index < lines.length;) {
    const line = lines[index]

    if (!line || /^\s*#/.test(line)) {
      index += 1
      continue
    }

    const match = line.match(/^([A-Za-z0-9_-]+):(?:\s*(.*))?$/)
    if (!match) {
      throw new Error(`${relative}: unsupported frontmatter line "${line}"`)
    }

    const key = match[1]
    const rawValue = match[2] ?? ''

    if (rawValue === '>' || rawValue === '|') {
      const blockLines = []
      index += 1

      while (index < lines.length && (lines[index] === '' || /^\s+/.test(lines[index]))) {
        blockLines.push(lines[index])
        index += 1
      }

      values[key] = rawValue === '>'
        ? foldBlock(blockLines)
        : stripCommonIndent(blockLines).join('\n')
      continue
    }

    values[key] = unquote(rawValue)
    index += 1
  }

  return values
}

function foldBlock(lines) {
  return stripCommonIndent(lines)
    .map(line => line.trim())
    .filter(Boolean)
    .join(' ')
}

function stripCommonIndent(lines) {
  const nonEmpty = lines.filter(line => line.trim())
  const minIndent = nonEmpty.reduce((min, line) => {
    const indent = line.match(/^\s*/)?.[0].length ?? 0
    return Math.min(min, indent)
  }, Number.POSITIVE_INFINITY)

  if (!Number.isFinite(minIndent)) {
    return []
  }

  return lines.map(line => line.slice(minIndent))
}

function unquote(value) {
  const trimmed = value.trim()

  if (
    (trimmed.startsWith('"') && trimmed.endsWith('"'))
    || (trimmed.startsWith("'") && trimmed.endsWith("'"))
  ) {
    return trimmed.slice(1, -1)
  }

  return trimmed
}

function stripBom(value) {
  return value.replace(/^\uFEFF/, '')
}

function renderCatalog(records) {
  return `// This file is generated by scripts/generate-skill-catalog.mjs.
// Do not edit it by hand.

export interface QuantumSkillCatalogEntry {
  readonly id: string
  readonly name: string
  readonly description: string
  readonly content: string
}

export const skills: readonly QuantumSkillCatalogEntry[] = ${JSON.stringify(records, null, 2)}
`
}
